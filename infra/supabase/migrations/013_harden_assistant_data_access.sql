CREATE OR REPLACE FUNCTION public.match_knowledge(
  query_embedding extensions.vector,
  match_threshold double precision,
  match_count integer
)
RETURNS TABLE (
  id bigint,
  content text,
  slug text,
  type text,
  metadata jsonb,
  similarity double precision
)
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = ''
AS $function$
  SELECT
    knowledge.id,
    knowledge.content,
    knowledge.slug,
    knowledge.type,
    knowledge.metadata,
    1 - (knowledge.embedding OPERATOR(extensions.<=>) query_embedding) AS similarity
  FROM public.knowledge AS knowledge
  WHERE 1 - (knowledge.embedding OPERATOR(extensions.<=>) query_embedding)
    > greatest(least(coalesce(match_threshold, 0.5), 1), -1)
  ORDER BY 1 - (knowledge.embedding OPERATOR(extensions.<=>) query_embedding) DESC
  LIMIT least(greatest(coalesce(match_count, 3), 1), 20);
$function$;

REVOKE ALL PRIVILEGES ON FUNCTION public.match_knowledge(extensions.vector, double precision, integer)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.match_knowledge(extensions.vector, double precision, integer)
  TO service_role;

