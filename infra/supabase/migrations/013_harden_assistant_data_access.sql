BEGIN;

CREATE SCHEMA IF NOT EXISTS extensions;

DO $migration$
DECLARE
  vector_schema text;
BEGIN
  SELECT namespace.nspname
    INTO vector_schema
    FROM pg_catalog.pg_extension AS extension
    JOIN pg_catalog.pg_namespace AS namespace
      ON namespace.oid = extension.extnamespace
   WHERE extension.extname = 'vector';

  IF vector_schema IS NULL THEN
    CREATE EXTENSION vector WITH SCHEMA extensions;
  ELSIF vector_schema <> 'extensions' THEN
    ALTER EXTENSION vector SET SCHEMA extensions;
  END IF;
END;
$migration$;

GRANT USAGE ON SCHEMA extensions TO service_role;

CREATE TABLE IF NOT EXISTS public.knowledge (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content text NOT NULL,
  slug text NOT NULL,
  type text NOT NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  embedding extensions.vector(384) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT knowledge_slug_content_key UNIQUE (slug, content)
);

ALTER TABLE public.knowledge ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.knowledge FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.knowledge TO service_role;

DO $migration$
DECLARE
  knowledge_id_sequence text;
BEGIN
  SELECT pg_catalog.pg_get_serial_sequence('public.knowledge', 'id')
    INTO knowledge_id_sequence;

  IF knowledge_id_sequence IS NOT NULL THEN
    EXECUTE pg_catalog.format(
      'GRANT USAGE, SELECT ON SEQUENCE %s TO service_role',
      knowledge_id_sequence
    );
  END IF;
END;
$migration$;

DO $migration$
